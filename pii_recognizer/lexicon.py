def make_surname_forms(surname: str) -> set[str]:

    return {
        surname, surname+'а', surname+'у', surname+'ым', surname+'ом',
        surname+'ой', surname+'у', surname+'е', surname+'ы',
        surname[:-2]+'ой' if surname.endswith(('ин', 'ын')) else surname+'ой',
    }

